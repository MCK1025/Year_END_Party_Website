-- One existing row is one Moment. Unedited legacy photos retain their original
-- references and order. A draft album replaces that representation on explicit save.
do $upgrade$
declare original_ids uuid[];
begin
  lock table private.recaps in access exclusive mode;
  select array_agg(r.id order by r.sort_order) into original_ids from private.recaps r;
  alter table private.recaps
    add column album jsonb check (jsonb_typeof(album) = 'object'),
    add column album_order bigint generated by default as identity,
    add column album_version uuid not null default gen_random_uuid();
  update private.recaps r set album_order=p.position
    from unnest(original_ids) with ordinality as p(id,position)
    where r.id=p.id and r.album_order<>p.position;
end $upgrade$;

create function private.recap_version() returns trigger language plpgsql set search_path='' as $$
begin
  new.album_version := gen_random_uuid();
  return new;
end $$;
create trigger recap_version before update on private.recaps
  for each row execute function private.recap_version();

create or replace function private.save_recap_album(p jsonb) returns void language plpgsql set search_path='' as $$
declare
  moment_id uuid := coalesce((p->>'id')::uuid,gen_random_uuid());
  previous private.recaps;
  book jsonb := p->'album';
begin
  select * into previous from private.recaps where id=moment_id for update;
  if book is not null then
    if not (p ? 'expected_version') or previous.album_version is distinct from (p->>'expected_version')::uuid then
      raise exception '장면이 변경되었습니다. 최신 내용을 다시 열어주세요.' using errcode='PT409';
    end if;
    if p->>'asset_path' is not null or jsonb_typeof(book->'slides') is distinct from 'array'
       or exists (select 1 from jsonb_array_elements(book->'slides') s group by s->>'id' having count(*) > 1) then
      raise exception '상세 장면의 형식을 확인해주세요.';
    end if;
  elsif previous.album is not null then
    raise exception '앨범 편집을 위해 관리자 화면을 새로고침해주세요.' using errcode='PT409';
  end if;
  if exists (
    select 1 from (
      select p->>'asset_path' as path union all select book->>'cover_path'
      union all select s->>'asset_path' from jsonb_array_elements(book->'slides') s
    ) refs where path is not null and not exists (
      select 1 from storage.objects where bucket_id='event-media' and name=refs.path
    )
  ) then raise exception '사진 업로드를 먼저 완료해주세요.'; end if;
  insert into private.recaps(id,caption,published,sort_order,asset_path,album)
    values(moment_id,p->>'caption',(p->>'published')::boolean,(p->>'sort_order')::int,p->>'asset_path',book)
    on conflict(id) do update set caption=excluded.caption,published=excluded.published,
      sort_order=excluded.sort_order,asset_path=excluded.asset_path,album=excluded.album;
end $$;
revoke all on function private.save_recap_album(jsonb),private.recap_version() from public,anon,authenticated;

-- Preserve all other action handlers, including their existing authorization,
-- locking, audit and event invalidation.
do $migration$
declare def text := pg_get_functiondef('private.admin_content(uuid,text,jsonb)'::regprocedure);
  start_at int := strpos(def,'when ''recap'' then');
  end_at int := strpos(def,'when ''delete_recap'' then');
begin
  if start_at=0 or end_at<=start_at then raise exception 'Unexpected recap handler'; end if;
  execute left(def,start_at-1) || 'when ''recap'' then perform private.save_recap_album(p); ' || substr(def,end_at);
end $migration$;

create or replace function public.can_read_media(p_path text) returns boolean
language sql stable security definer set search_path='' as $$
  select public.is_admin() or (public.current_employee() is not null and (
    p_path=(select logo_path from private.settings) or
    (public.content_open() and exists(select 1 from public.event_public_state where phase='RECAP')
     and exists(select 1 from private.recaps r where r.published and
       (r.asset_path=p_path or r.album->>'cover_path'=p_path or
        (r.album->'slides') @> jsonb_build_array(jsonb_build_object('asset_path',p_path)))))
  ));
$$;
